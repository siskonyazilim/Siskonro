/**
 * Tüm blog postlarını getirir
 */
export function getAllBlogPosts() {
  return [...BLOG_POSTS];
}

/**
 * Slug'a göre tek bir blog postu getirir
 * @param {string} slug
 */
export function getBlogPostBySlug(slug) {
  return BLOG_POSTS.find((post) => post.slug === slug) || null;
}

/**
 * Son N adet blog postu getirir (ana sayfa için)
 * @param {number} count
 */
export function getLatestBlogPosts(count = 4) {
  return getAllBlogPosts().slice(0, count);
}

/**
 * Tüm slug'ları getirir (Next.js static params için)
 */
export function getAllBlogSlugs() {
  return BLOG_POSTS.map((post) => post.slug);
}
